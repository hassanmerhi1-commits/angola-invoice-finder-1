/** On INSERT, keep explicit warehouse id so inventory grid lists zero-stock products (branch_id = $1). */
async function resolveStoredBranchIdForCreate(branchId) {
  const key = branchId == null ? '' : String(branchId).trim();
  if (!key) return null;
  if (db.engine === 'sqlite') return key;
  const uuid = sanitizeUuid(key);
  return uuid || null;
}

async function findExistingProductForUpsert({ sku, name, branchId }) {
  const skuTrim = String(sku || '').trim();
  const nameTrim = String(name || '').trim();
  const storedBranchId = await resolveStoredBranchId(branchId);

  if (skuTrim) {
    const bySku = await findExistingProductBySku(skuTrim, storedBranchId ?? branchId);
    if (bySku) return { id: bySku, matchedBy: 'sku' };
    // Typed SKU not found — never fall back to name match (that steals the new
    // code onto an old row and makes Inventory look like the product was never created).
    return null;
  }

  // Name match only when SKU is empty / auto — used for Adjust In style upserts.
  if (nameTrim) {
    const byName = await findExistingProductByName(nameTrim, storedBranchId ?? branchId);
    if (byName?.id) return { id: byName.id, matchedBy: 'name', existingSku: byName.sku };
  }

  return null;
}

/** One row per SKU when duplicate branch/catalog rows exist (e.g. after repeated transfers). */
function dedupeProductsBySku(rows, branchId, mainBranchIds = []) {
  const bySku = new Map();
  for (const row of rows) {
    const key = dedupeRowKey(row, mainBranchIds);
    const prev = bySku.get(key);
    if (!prev) {
      bySku.set(key, row);
      continue;
    }
    const pick = rowDisplayScore(row, branchId, mainBranchIds) >= rowDisplayScore(prev, branchId, mainBranchIds) ? row : prev;
    const other = pick === row ? prev : row;
    const scopedBranch = String(branchId || '').trim();
    bySku.set(key, {
      ...pick,
      stock: scopedBranch
        ? Number(pick.stock) || 0
        : Math.max(Number(pick.stock) || 0, Number(other.stock) || 0),
      supplier_id: pick.supplier_id || other.supplier_id || null,
      supplier_name: pick.supplier_name || other.supplier_name || null,
    });
  }

  const merged = [];
  for (const row of bySku.values()) {
    const index = merged.findIndex((existing) => shouldMergeProductDuplicates(existing, row, mainBranchIds));
    if (index < 0) {
      merged.push(row);
      continue;
    }
    const prev = merged[index];
    const pick = rowDisplayScore(row, branchId, mainBranchIds) >= rowDisplayScore(prev, branchId, mainBranchIds) ? row : prev;
    const other = pick === row ? prev : row;
    const scopedBranch = String(branchId || '').trim();
    merged[index] = {
      ...pick,
      stock: scopedBranch
        ? Number(pick.stock) || 0
        : Math.max(Number(pick.stock) || 0, Number(other.stock) || 0),
      supplier_id: pick.supplier_id || other.supplier_id || null,
      supplier_name: pick.supplier_name || other.supplier_name || null,
    };
  }
  return merged;
}

