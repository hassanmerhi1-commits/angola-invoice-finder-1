  // Update product (with optimistic locking)
  router.put('/:id', requirePermission('inventory_edit'), async (req, res) => {
    try {
      const { id } = req.params;
      const existingResult = await db.query('SELECT * FROM products WHERE id = $1', [id]);
      if (!existingResult.rows[0]) {
        return res.status(404).json({ error: 'Product not found' });
      }
      const existing = existingResult.rows[0];
      const {
        name, sku, barcode, category, price, price2, price3, price4, cost, stock, unit, taxRate,
        branchId, isActive, version, supplierId, supplierName, lastCost, avgCost, preserveStock,
      } = req.body;
      const mergedName = name != null && name !== '' ? name : existing.name;
      const mergedSku = sku != null && sku !== '' ? sku : existing.sku;
      const mergedBarcode = barcode != null ? barcode : existing.barcode;
      const mergedCategory = category != null && category !== '' ? category : existing.category;
      const mergedPrice = price != null && price !== '' ? price : existing.price;
      // Price tiers 2-4: only overwrite when a positive value is supplied. A 0/blank means
      // "tier not set" for this request, so keep the stored value instead of wiping it
      // (purchase/stock/physical-count updates send these as 0).
      const mergedPrice2 = price2 != null && price2 !== '' && Number(price2) > 0 ? Number(price2) : existing.price2;
      const mergedPrice3 = price3 != null && price3 !== '' && Number(price3) > 0 ? Number(price3) : existing.price3;
      const mergedPrice4 = price4 != null && price4 !== '' && Number(price4) > 0 ? Number(price4) : existing.price4;
      const mergedCost = cost != null && cost !== '' ? cost : existing.cost;
      const mergedStock = stock != null && stock !== '' ? stock : existing.stock;
      const mergedUnit = unit != null && unit !== '' ? unit : existing.unit;
      const mergedTaxRate = taxRate != null && taxRate !== '' ? taxRate : existing.tax_rate;
      const mergedBranchId =
        resolveProductBranchId(req, branchId) ?? sanitizeUuid(branchId) ?? existing.branch_id;
      const mergedIsActive = isActive !== false && isActive !== 0 ? 1 : isActive === false || isActive === 0 ? 0 : existing.is_active;
      const mergedSupplierId = supplierId != null ? sanitizeUuid(supplierId) : existing.supplier_id;
      const mergedSupplierName = supplierName != null ? supplierName : existing.supplier_name;
      const keepStock = preserveStock === true || preserveStock === 'true' || preserveStock === 1;
      const setClause = keepStock
        ? `name=$1, sku=$2, barcode=$3, category=$4, price=$5, cost=$6, stock=stock,
           unit=$7, tax_rate=$8, branch_id=$9, is_active=$10,
           price2=$11, price3=$12, price4=$13,
           supplier_id=$14, supplier_name=$15,
           last_cost=COALESCE($16, last_cost), avg_cost=COALESCE($17, avg_cost)`
        : `name=$1, sku=$2, barcode=$3, category=$4, price=$5, cost=$6, stock=$7,
           unit=$8, tax_rate=$9, branch_id=$10, is_active=$11,
           price2=$12, price3=$13, price4=$14,
           supplier_id=$15, supplier_name=$16,
           last_cost=COALESCE($17, last_cost), avg_cost=COALESCE($18, avg_cost)`;
      const updateParams = keepStock
        ? [mergedName, mergedSku, mergedBarcode, mergedCategory, mergedPrice, mergedCost, mergedUnit, mergedTaxRate,
           mergedBranchId,
           mergedIsActive,
           mergedPrice2 || 0, mergedPrice3 || 0, mergedPrice4 || 0,
           mergedSupplierId, mergedSupplierName || null,
           lastCost ?? null, avgCost ?? null]
        : [mergedName, mergedSku, mergedBarcode, mergedCategory, mergedPrice, mergedCost, mergedStock, mergedUnit, mergedTaxRate,
           mergedBranchId,
           mergedIsActive,
           mergedPrice2 || 0, mergedPrice3 || 0, mergedPrice4 || 0,
           mergedSupplierId, mergedSupplierName || null,
           lastCost ?? null, avgCost ?? null];
      
      let result;
      if (version != null) {
        result = await db.query(
          `UPDATE products 
           SET ${setClause},
               version = version + 1
           WHERE id=$${updateParams.length + 1} AND version=$${updateParams.length + 2}
           RETURNING *`,
          [...updateParams, id, version]
        );
        if (!checkOptimisticLock(result, res, 'Product')) return;
      } else {
        result = await db.query(
          `UPDATE products 
           SET ${setClause}
           WHERE id=$${updateParams.length + 1}
           RETURNING *`,
          [...updateParams, id]
        );
        if (result.rowCount === 0) {
          return res.status(404).json({ error: 'Product not found' });
        }
      }
      
      const updated = result.rows[0];
      const skuKey = String(updated?.sku || '').trim();
      if (skuKey) {
        if (taxRate != null && taxRate !== '') {
          await db.query(
            `UPDATE products
             SET tax_rate = $1, updated_at = CURRENT_TIMESTAMP
             WHERE ${coalesceActiveNotZero(db, 'is_active')}
               AND LOWER(TRIM(COALESCE(sku, ''))) = LOWER($2)`,
            [Number(taxRate), skuKey]
          );
        }
        if (price != null && price !== '') {
          // Propagate the price tiers to every branch row sharing this SKU, but never
          // overwrite an existing tier with 0/blank: routine updates (purchases, stock
          // adjustments, physical counts) send price2-4 = 0 and would otherwise wipe them.
          // Pass null (not 0) for "no value" so COALESCE keeps the stored tier. Do NOT use
          // a `$n > 0` test: PostgreSQL infers such a param as integer and rejects decimal
          // tiers (e.g. 739.98) with "invalid input syntax for type integer".
          const skuTier = (v) => (Number(v) > 0 ? Number(v) : null);
          await db.query(
            `UPDATE products
             SET price = $1,
                 price2 = COALESCE($2, price2),
                 price3 = COALESCE($3, price3),
                 price4 = COALESCE($4, price4),
                 updated_at = CURRENT_TIMESTAMP
             WHERE ${coalesceActiveNotZero(db, 'is_active')}
               AND LOWER(TRIM(COALESCE(sku, ''))) = LOWER($5)`,
            [Number(price), skuTier(price2), skuTier(price3), skuTier(price4), skuKey]
          );
        }
        const costVal = cost != null && cost !== '' ? Number(cost) : null;
        if (costVal != null && !Number.isNaN(costVal)) {
          const lastVal = lastCost != null && lastCost !== '' ? Number(lastCost) : costVal;
          const avgVal = avgCost != null && avgCost !== '' ? Number(avgCost) : costVal;
          await db.query(
            `UPDATE products
             SET cost = $1, last_cost = $2, avg_cost = $3, updated_at = CURRENT_TIMESTAMP
             WHERE ${coalesceActiveNotZero(db, 'is_active')}
               AND LOWER(TRIM(COALESCE(sku, ''))) = LOWER($4)`,
            [costVal, lastVal, avgVal, skuKey],
          );
        }
      }

      invalidateSellingHintsCache();
      await broadcastTable('products');
      res.json(updated);
    } catch (error) {
      console.error('[PRODUCTS ERROR]', error);
      res.status(500).json({ error: 'Failed to update product' });
    }
  });

