/**
 * Money/IVA shown for a merged SKU must belong to the row we actually display.
 *
 * The grid hands `pick.id` to the product detail dialog, which reads that row straight from
 * the DB — so blending a MAX price/cost (or a sibling's non-default IVA) across duplicate
 * rows made the grid show one row's numbers and the dialog another ("outside different from
 * inside"), and made the same SKU differ per branch depending on which duplicates that
 * branch's query happened to return. Only fill a genuinely empty (0 / NULL) field.
 */
function taxRatePickScore(rate) {
  if (rate === null || rate === undefined || rate === '') return 0;
  const n = Number(rate);
  if (!Number.isFinite(n)) return 0;
  // Legacy 5% import default loses to an intentionally chosen rate (0, 7, 14).
  return Math.abs(n - 5) > 0.0001 ? 2 : 1;
}

function preferDisplayTaxRate(pick, other) {
  const ps = taxRatePickScore(pick?.tax_rate);
  const os = taxRatePickScore(other?.tax_rate);
  if (ps > os) return pick.tax_rate;
  if (os > ps) return other.tax_rate;
  if (pick?.tax_rate !== null && pick?.tax_rate !== undefined && pick?.tax_rate !== '') {
    return pick.tax_rate;
  }
  return other?.tax_rate;
}

function mergeDisplayFields(pick, other) {
  const fillN = (a, b) => (Number(a) > 0.0001 ? Number(a) : Number(b) || 0);
  return {
    price: fillN(pick.price, other.price),
    cost: fillN(pick.cost, other.cost),
    first_cost: fillN(pick.first_cost, other.first_cost),
    last_cost: fillN(pick.last_cost, other.last_cost),
    avg_cost: fillN(pick.avg_cost, other.avg_cost),
    tax_rate: preferDisplayTaxRate(pick, other),
  };
}

function mergeGridSkuRow(prev, row, warehouseBranchId, mainBranchIds = []) {
  const pick =
    rowDisplayScore(row, warehouseBranchId, mainBranchIds)
    >= rowDisplayScore(prev, warehouseBranchId, mainBranchIds)
      ? row
      : prev;
  const other = pick === row ? prev : row;
  const scoped = String(warehouseBranchId || '').trim();
  const maxN = (a, b) => Math.max(Number(a) || 0, Number(b) || 0);
  // One physical row per grid line — never blend price/IVA from a sibling row onto pick.id
  // or the list disagrees with GET /products/:id (the detail dialog).
  return {
    ...pick,
    stock: scoped ? Number(pick.stock) || 0 : maxN(pick.stock, other.stock),
    supplier_id: pick.supplier_id || other.supplier_id || null,
    supplier_name: pick.supplier_name || other.supplier_name || null,
  };
}

function dedupeRowsBySkuFast(rows, warehouseBranchId, mainBranchIds = []) {
  const bySku = new Map();
  for (const row of rows) {
    const key = normalizeSkuKey(row.sku) || String(row.id);
    const prev = bySku.get(key);
    if (!prev) {
      bySku.set(key, row);
      continue;
    }
    bySku.set(key, mergeGridSkuRow(prev, row, warehouseBranchId, mainBranchIds));
  }
  return Array.from(bySku.values());
}

/** One scan of movements per warehouse → stock by SKU (accurate qty, fast). */
function sqlStockBySkuCte() {
  const skuKey = sqlMovementSkuKey('pm');
  return `
    stock_by_sku AS (
      SELECT
        ${skuKey} AS sku_key,
        CASE
          WHEN COALESCE(SUM(
            CASE
              WHEN sm.movement_type = 'IN' THEN sm.quantity
              WHEN sm.movement_type = 'OUT' THEN -sm.quantity
              ELSE 0
            END
          ), 0) < 0 THEN 0
          ELSE COALESCE(SUM(
            CASE
              WHEN sm.movement_type = 'IN' THEN sm.quantity
              WHEN sm.movement_type = 'OUT' THEN -sm.quantity
              ELSE 0
            END
          ), 0)
        END AS ledger_stock
      FROM stock_movements sm
      INNER JOIN products pm ON pm.id = sm.product_id
      WHERE sm.warehouse_id = $1
      GROUP BY ${skuKey}
    )`;
}

