  // Batch import products (SQLite + PostgreSQL)
  router.post('/batch', requirePermission('inventory_import', 'inventory_create'), async (req, res) => {
    try {
      const { products: productList } = req.body;
      if (!Array.isArray(productList) || productList.length === 0) {
        return res.status(400).json({ error: 'products array is required' });
      }

      let inserted = 0;
      let updated = 0;
      let failed = 0;
      const errors = [];

      for (const p of productList) {
        const rawSku = String(p?.sku ?? p?.codigo ?? p?.code ?? '').trim();
        const rawName = String(p?.name ?? p?.descricao ?? p?.description ?? p?.designacao ?? '').trim();
        const branchId = resolveProductBranchId(req, p.branchId);
        if (branchId === undefined) {
          failed += 1;
          errors.push({ sku: rawSku || rawName || '?', error: 'Sem filial atribuída' });
          continue;
        }
        const cost = Number(p.cost) || 0;
        const stock = Number(p.stock ?? p.quantidade) || 0;
        const activeInt = p.isActive !== false ? 1 : 0;

        let sku = rawSku;
        let existingId = null;
        let existingMatch = null;

        if (sku || rawName) {
          existingMatch = await findExistingProductForUpsert({
            sku: rawSku,
            name: rawName,
            branchId,
          });
        }

        if (existingMatch?.id) {
          existingId = existingMatch.id;
          if (existingMatch.existingSku && String(existingMatch.existingSku).trim()) {
            sku = String(existingMatch.existingSku).trim();
          } else if (!sku) {
            sku = rawName;
          }
        } else if (!sku && rawName) {
          sku = `AUTO-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
        }

        if (!sku) {
          sku = `AUTO-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
        }
        const name = rawName || sku;
        const storedBranchId = await resolveStoredBranchId(branchId);

        try {
          if (existingId) {
            const upd = await db.query(
              `UPDATE products
               SET name = $1, sku = $2, barcode = $3, category = $4, price = $5, cost = $6,
                   stock = $7, unit = $8, tax_rate = $9, branch_id = $10,
                   supplier_id = $11, supplier_name = $12, is_active = $13,
                   last_cost = COALESCE($6, last_cost), avg_cost = COALESCE($6, avg_cost),
                   updated_at = CURRENT_TIMESTAMP
               WHERE id = $14`,
              [
                name,
                sku,
                p.barcode || '',
                p.category || 'GERAL',
                Number(p.price) || 0,
                cost,
                stock,
                String(p.unit || p.unidade || 'UN'),
                Number(p.taxRate ?? p.iva) || DEFAULT_VAT_RATE,
                storedBranchId,
                sanitizeUuid(p.supplierId),
                p.supplierName || null,
                activeInt,
                existingId,
              ],
            );
            if (upd.rowCount > 0) updated++;
          } else {
            const id = crypto.randomUUID();
            const ins = await db.query(
              `INSERT INTO products (id, name, sku, barcode, category, price, price2, price3, price4, cost, first_cost, last_cost, avg_cost, stock, unit, tax_rate, branch_id, is_active, supplier_id, supplier_name)
               VALUES ($1, $2, $3, $4, $5, $6, 0, 0, 0, $7, $7, $7, $7, $8, $9, $10, $11, $12, $13, $14)`,
              [
                id,
                name,
                sku,
                p.barcode || '',
                p.category || 'GERAL',
                Number(p.price) || 0,
                cost,
                stock,
                String(p.unit || p.unidade || 'UN'),
                Number(p.taxRate ?? p.iva) || DEFAULT_VAT_RATE,
                storedBranchId,
                activeInt,
                sanitizeUuid(p.supplierId),
                p.supplierName || null,
              ],
            );
            if (ins.rowCount > 0) inserted++;
          }
        } catch (err) {
          failed++;
          const rowError = err?.message || String(err);
          console.error('[PRODUCTS IMPORT ROW ERROR]', rowError, { sku });
          errors.push({ sku, error: rowError });
        }
      }

      console.log(`[PRODUCTS IMPORT] inserted=${inserted} updated=${updated} failed=${failed}`);
      await broadcastTable('products');
      res.status(201).json({ imported: inserted, updated, failed, errors: errors.slice(0, 50) });
    } catch (error) {
      console.error('[PRODUCTS BATCH ERROR]', error);
      res.status(500).json({ error: 'Failed to batch import products' });
    }
  });

  // Delete product (soft delete) — only when no stock movements or sales exist
  router.delete('/:id', async (req, res) => {
    try {
      const { id } = req.params;
      const counts = await productTransactionCounts(id);
      if (!counts.deletable) {
        return res.status(409).json({
          error: 'Product has stock movements or sales and cannot be deleted',
          ...counts,
        });
      }

      await db.query('UPDATE products SET is_active = false WHERE id = $1', [id]);

      await broadcastTable('products');
      res.json({ success: true });
    } catch (error) {
      console.error('[PRODUCTS ERROR]', error);
      res.status(500).json({ error: 'Failed to delete product' });
    }
  });

  return router;
