function enrichInventoryGridSellingPrices(rows, priceBySku) {
  if (!priceBySku?.size) return rows;
  return rows.map((row) => {
    // Price 1 is the authoritative base price entered on the product. Only SEED it from the
    // selling-price hint when it is missing (zero); never RAISE a real price1, otherwise
    // POS/sales price-level selection (level 1 = price1) would resolve to a blended value.
    const cur = Number(row.price) || 0;
    if (cur > 0) return row;
    const key = canonicalSkuString(row.sku).toLowerCase();
    if (!key) return row;
    const hint = Number(priceBySku.get(key) || 0);
    if (hint <= 0) return row;
    return { ...row, price: hint };
  });
}

function priceOverrideIsFalseSql() {
  return db.engine === 'postgres'
    ? 'COALESCE(price_override, false) = false'
    : 'COALESCE(price_override, 0) = 0';
}

/** Seed hinted selling price only when price1 is still zero (never raise / fight HQ cuts). */
async function persistSellingPricesFromHints(priceBySku) {
  if (!priceBySku?.size) return 0;
  let updated = 0;
  for (const [skuKey, price] of priceBySku) {
    const p = Number(price);
    if (!skuKey || p <= 0) continue;
    const result = await db.query(
      `UPDATE products
       SET price = $1, updated_at = CURRENT_TIMESTAMP
       WHERE ${coalesceActiveNotZero(db, 'is_active')}
         AND ${sqlMovementSkuKey('products')} = LOWER($2)
         AND COALESCE(price, 0) <= 0
         AND ${priceOverrideIsFalseSql()}`,
      [p, skuKey],
    );
    updated += result.rowCount || 0;
  }
  return updated;
}

/**
 * Propagate price tiers from HQ/Sede to every active SKU sibling that has not opted into a local override.
 * Uses canonical SKU (strips -DUP-…) so filial repair rows stay in sync.
 */
async function cascadeSkuPricesFromHq(skuRaw, price, price2, price3, price4, opts = {}) {
  const canon = canonicalSkuString(skuRaw).toLowerCase();
  if (!canon) return 0;
  const skuTier = (v) => (Number(v) > 0 ? Number(v) : null);
  // includeOverridden: an HQ save reaches even branches that once kept their own price, and
  // releases them, so one stale flag cannot keep a branch on a different price forever.
  const overrideClause = opts.includeOverridden ? '' : `AND ${priceOverrideIsFalseSql()}`;
  const clearOptOut = opts.includeOverridden
    ? `, price_override = ${db.engine === 'postgres' ? 'false' : '0'}`
    : '';
  const result = await db.query(
    `UPDATE products
     SET price = $1,
         price2 = COALESCE($2, price2),
         price3 = COALESCE($3, price3),
         price4 = COALESCE($4, price4)${clearOptOut},
         updated_at = CURRENT_TIMESTAMP
     WHERE ${coalesceActiveNotZero(db, 'is_active')}
       AND ${sqlMovementSkuKey('products')} = $5
       ${overrideClause}`,
    [Number(price), skuTier(price2), skuTier(price3), skuTier(price4), canon],
  );
  return result.rowCount || 0;
}

