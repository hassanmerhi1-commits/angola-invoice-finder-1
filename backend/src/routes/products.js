/** Avoid running full filial reconcile on every grid poll (locks SQLite, trips health checks). */
const filialGridReconcileAt = new Map();
const FILIAL_GRID_RECONCILE_COOLDOWN_MS = 120_000;

async function ensureFilialForInventoryGrid(branchKey) {
  const key = String(branchKey || '').trim();
  if (!key) return;
  const now = Date.now();
  const last = filialGridReconcileAt.get(key) || 0;
  if (now - last < FILIAL_GRID_RECONCILE_COOLDOWN_MS) return;
  filialGridReconcileAt.set(key, now);
  try {
    await ensureFilialProductsForWarehouse(key);
  } catch (err) {
    filialGridReconcileAt.delete(key);
    console.warn('[PRODUCTS inventory-grid] filial stock reconcile:', err.message);
  }
}

function sanitizeUuid(value) {
  if (typeof value !== 'string') return value ?? null;
  const trimmed = value.trim();
  if (!trimmed) return null;
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(trimmed) ? trimmed : null;
}

/** Preserve text branch ids (e.g. branch-main) on SQLite; UUID on Postgres when valid. */
function resolveProductBranchId(req, requestedBranchId) {
  const scoped = resolveListBranchId(req, requestedBranchId);
  if (scoped === undefined) return undefined;
  if (!scoped) return null;
  const key = String(scoped).trim();
  if (!key || key === 'all') return null;
  if (db.engine === 'sqlite') return key;
  const uuid = sanitizeUuid(key);
  if (!uuid) {
    console.warn('[PRODUCTS] Ignoring invalid branchId for Postgres:', key);
    return resolveListBranchId(req, null);
  }
  return uuid;
}

function normalizeSkuKey(sku) {
  return canonicalSkuString(sku).toLowerCase();
}

function normalizeCatalogBranchKey(branchId, mainBranchIds = []) {
  const value = String(branchId ?? '').trim();
  if (!value) return 'catalog';
  if (mainBranchIds.includes(value)) return 'catalog';
  return value;
}

function normalizeNameKey(name) {
  return String(name || '')
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ');
}

function skuLooksAutoGenerated(sku) {
  const value = String(sku || '').trim();
  if (!value) return true;
  return /^AUTO-/i.test(value) || /^SKU-\d{10,}/i.test(value);
}

function rowDisplayScore(row, branchId, mainBranchIds = []) {
  const stock = Number(row.stock || 0);
  const rowBranch = String(row.branch_id || '').trim();

  if (branchId && rowBranch === String(branchId)) {
    return 2_000_000 + stock;
  }

  if (branchId) {
    let score = stock;
    if (!rowBranch) score += 500_000;
    else if (!isCatalogBranchScope(rowBranch, mainBranchIds)) score += 50_000;
    if (!skuLooksAutoGenerated(row.sku)) score += 50;
    if (String(row.barcode || '').trim()) score += 25;
    score += taxRatePickScore(row.tax_rate) * 10_000;
    return score;
  }

  let score = stock * 1000;
  if (normalizeCatalogBranchKey(row.branch_id, mainBranchIds) === 'catalog' && !rowBranch) {
    score += 500;
  }
  if (rowBranch) score += 100;
  if (!skuLooksAutoGenerated(row.sku)) score += 50;
  if (String(row.barcode || '').trim()) score += 25;
  score += taxRatePickScore(row.tax_rate) * 10_000;
  return score;
}

function shouldMergeProductDuplicates(a, b, mainBranchIds = []) {
  const nameA = normalizeNameKey(a.name);
  const nameB = normalizeNameKey(b.name);
  if (!nameA || nameA !== nameB) return false;
  const branchA = normalizeCatalogBranchKey(a.branch_id, mainBranchIds);
  const branchB = normalizeCatalogBranchKey(b.branch_id, mainBranchIds);
  if (branchA !== branchB) return false;
  const skuA = normalizeSkuKey(a.sku);
  const skuB = normalizeSkuKey(b.sku);
  if (skuA && skuB && skuA === skuB) return true;
  const barcodeA = String(a.barcode || '').trim().toLowerCase();
  const barcodeB = String(b.barcode || '').trim().toLowerCase();
  if (barcodeA && barcodeB && barcodeA === barcodeB) return true;
  if (skuLooksAutoGenerated(a.sku) || skuLooksAutoGenerated(b.sku)) return true;
  return true;
}

function dedupeRowKey(row, mainBranchIds = []) {
  const scope = normalizeCatalogBranchKey(row.branch_id, mainBranchIds);
  const skuKey = normalizeSkuKey(row.sku);
  if (skuKey && !skuLooksAutoGenerated(row.sku)) {
    return `${scope}|sku:${skuKey}`;
  }
  const nameKey = normalizeNameKey(row.name);
  return `${scope}|name:${nameKey || row.id}`;
}

