function mergeGridSkuRow(prev, row, warehouseBranchId, mainBranchIds = []) {
  const pick =
    rowDisplayScore(row, warehouseBranchId, mainBranchIds)
    >= rowDisplayScore(prev, warehouseBranchId, mainBranchIds)
      ? row
      : prev;
  const other = pick === row ? prev : row;
  const scoped = String(warehouseBranchId || '').trim();
  const maxN = (a, b) => Math.max(Number(a) || 0, Number(b) || 0);
  return {
    ...pick,
    stock: scoped ? Number(pick.stock) || 0 : maxN(pick.stock, other.stock),
    price: maxN(pick.price, other.price),
    cost: maxN(pick.cost, other.cost),
    first_cost: maxN(pick.first_cost, other.first_cost),
    last_cost: maxN(pick.last_cost, other.last_cost),
    avg_cost: maxN(pick.avg_cost, other.avg_cost),
  };
}

function dedupeRowsBySkuFast(rows, warehouseBranchId, mainBranchIds = []) {
  const bySku = new Map();
  for (const row of rows) {
    const key = normalizeSkuKey(row.sku) || String(row.id);
    const prev = bySku.get(key);
    if (!prev) {
      bySku.set(key, row);
      continue;
    }
    bySku.set(key, mergeGridSkuRow(prev, row, warehouseBranchId, mainBranchIds));
  }
  return Array.from(bySku.values());
}

/** One scan of movements per warehouse → stock by SKU (accurate qty, fast). */
function sqlStockBySkuCte() {
  const skuKey = sqlMovementSkuKey('pm');
  return `
    stock_by_sku AS (
      SELECT
        ${skuKey} AS sku_key,
        CASE
          WHEN COALESCE(SUM(
            CASE
              WHEN sm.movement_type = 'IN' THEN sm.quantity
              WHEN sm.movement_type = 'OUT' THEN -sm.quantity
              ELSE 0
            END
          ), 0) < 0 THEN 0
          ELSE COALESCE(SUM(
            CASE
              WHEN sm.movement_type = 'IN' THEN sm.quantity
              WHEN sm.movement_type = 'OUT' THEN -sm.quantity
              ELSE 0
            END
          ), 0)
        END AS ledger_stock
      FROM stock_movements sm
      INNER JOIN products pm ON pm.id = sm.product_id
      WHERE sm.warehouse_id = $1
      GROUP BY ${skuKey}
    )`;
}

/**
 * Stock for this warehouse only.
 * Catalog/master rows (branch_id != warehouse) must NOT use products.stock from sede — that caused
 * Soyo showing Main qty and HQ totals doubling when summing filiais.
 */
/** Hide catalog only when an active filial row exists for the same SKU (not merely same name). */
function sqlHideCatalogWhenFilialHasSameSku() {
  return `
            AND NOT EXISTS (
              SELECT 1 FROM products bx
              WHERE ${productActive('bx')}
                AND bx.branch_id = $1
                AND TRIM(COALESCE(p.sku, '')) != ''
                AND LOWER(TRIM(COALESCE(bx.sku, ''))) = LOWER(TRIM(p.sku))
            )`;
}

/** Pick one display row per SKU: filial row first, then row with most movements at this warehouse. */
function sqlPickProductIdForSkuAtWarehouse(catalogPickClause) {
  const p2Key = sqlMovementSkuKey('p2');
  return `
            p.id = (
              SELECT p2.id
              FROM products p2
              WHERE ${p2Key} = ms.sku_key
                AND (
                  p2.branch_id = $1
                  OR ${catalogPickClause}
                  OR p2.id IN (
                    SELECT DISTINCT sm.product_id
                    FROM stock_movements sm
                    WHERE sm.warehouse_id = $1
                  )
                )
              ORDER BY
                CASE WHEN COALESCE(p2.sku, '') LIKE '%-DUP-%' THEN 1 ELSE 0 END,
                CASE WHEN p2.branch_id = $1 THEN 0 ELSE 1 END,
                (
                  SELECT COUNT(*)
                  FROM stock_movements sm
                  WHERE sm.product_id = p2.id
                    AND sm.warehouse_id = $1
                ) DESC,
                p2.updated_at DESC,
                p2.created_at DESC
              LIMIT 1
            )`;
}

function sqlGridStockExpr(alias = 'p', warehouseBranchParam = '$1') {
  return `CASE
            WHEN ${alias}.branch_id = ${warehouseBranchParam} THEN
              CASE
                WHEN COALESCE(sbs.ledger_stock, ${alias}.stock, 0) < 0 THEN 0
                ELSE COALESCE(sbs.ledger_stock, ${alias}.stock, 0)
              END
            ELSE
              CASE
                WHEN COALESCE(sbs.ledger_stock, 0) < 0 THEN 0
                ELSE COALESCE(sbs.ledger_stock, 0)
              END
          END`;
}

/** Row-level PVP for grid SQL — cross-SKU hints applied after query via enrichRowsWithSellingPrices. */
function sqlGridRowPriceExpr(alias = 'p') {
  // Price 1 is the authoritative base price (entered manually). Do NOT blend it with
  // price2 — POS/sales select a tier by level, and returning MAX(price, price2) here
  // made level 1 (and any empty tier that falls back to `price`) resolve to price2.
  return `COALESCE(${alias}.price, 0)`;
}

/** Inventory-grid display price: keep real price1; only fill zeros from siblings / price2. */
function sqlGridDisplayPriceExpr(alias = 'p') {
  return `CASE
    WHEN COALESCE(${alias}.price, 0) > 0.0001 THEN COALESCE(${alias}.price, 0)
    ELSE ${sqlGridSellingPriceExpr(alias)}
  END`;
}

/** Latest purchase/transfer IN unit cost for this product at the active warehouse ($1). */
function sqlLastInUnitCostExpr(alias = 'p') {
  return `(
    SELECT sm.unit_cost
    FROM stock_movements sm
    WHERE sm.product_id = ${alias}.id
      AND sm.warehouse_id = $1
      AND sm.movement_type = 'IN'
      AND COALESCE(sm.unit_cost, 0) > 0.0001
    ORDER BY sm.created_at DESC
    LIMIT 1
  )`;
}

/** Cost column for inventory grid — fill zeros from last stock IN. */
function sqlGridDisplayCostExpr(alias, field) {
  return `CASE
    WHEN COALESCE(${alias}.${field}, 0) > 0.0001 THEN ${alias}.${field}
    ELSE COALESCE(${sqlLastInUnitCostExpr(alias)}, ${alias}.cost, 0)
  END`;
}

/** Best selling price for this SKU across catalog + filial rows (fixes Qtd > 0 filial-only rows). */
function sqlGridSellingPriceExpr(alias = 'p') {
  const rowPvp = sqlScalarMax(db, `COALESCE(${alias}.price, 0)`, `COALESCE(${alias}.price2, 0)`);
  const pxWhere = `
    WHERE ${productActive('px')}
      AND TRIM(COALESCE(px.sku, '')) != ''
      AND ${sqlMovementSkuKey('px')} = ${sqlMovementSkuKey(alias)}`;
  const siblingMax = isPostgresEngine(db)
    ? `(
    SELECT MAX(sub_val)
    FROM (
      SELECT ${sqlScalarMax(db, 'COALESCE(px.price, 0)', 'COALESCE(px.price2, 0)')} AS sub_val
      FROM products px
      ${pxWhere}
    ) sku_prices
  )`
    : `(
    SELECT MAX(MAX(COALESCE(px.price, 0), COALESCE(px.price2, 0)))
    FROM products px
    ${pxWhere}
  )`;
  return sqlScalarMax(db, rowPvp, `COALESCE(${siblingMax}, 0)`);
}

/** Inventory grid filial: show every SKU with stock movements at this warehouse (transfer receive). */
async function listProductsForBranchInventoryGrid(branchKey) {
  const mainBranchIds = await loadMainBranchIds();
  const rowPrice = sqlGridDisplayPriceExpr('p');
  const rowCost = sqlGridDisplayCostExpr('p', 'cost');
  const rowFirstCost = sqlGridDisplayCostExpr('p', 'first_cost');
  const rowLastCost = sqlGridDisplayCostExpr('p', 'last_cost');
  const rowAvgCost = sqlGridDisplayCostExpr('p', 'avg_cost');
  const mainIn =
    mainBranchIds.length > 0
      ? mainBranchIds.map((_, i) => `$${i + 2}`).join(', ')
      : "''";
  const params = [branchKey, ...mainBranchIds];
  const catalogBranchClause = catalogBranchScopeClause(db, 'p', mainIn);
  const catalogPickClause = catalogBranchScopeClause(db, 'p2', mainIn);

  const query = `
          WITH ${sqlStockBySkuCte()},
          movement_skus AS (
            SELECT sku_key, ledger_stock
            FROM stock_by_sku
            WHERE ledger_stock > 0.0001
          )
          SELECT
            p.id,
            p.name,
            p.sku,
            p.barcode,
            p.category,
            ${rowPrice} AS price,
            p.price2,
            p.price3,
            p.price4,
            ${rowCost} AS cost,
            ${rowFirstCost} AS first_cost,
            ${rowLastCost} AS last_cost,
            ${rowAvgCost} AS avg_cost,
            COALESCE(ms.ledger_stock, sbs.ledger_stock, 0) AS stock,
            p.unit,
            p.tax_rate,
            CASE WHEN p.branch_id = $1 THEN p.branch_id ELSE $1 END AS branch_id,
            p.supplier_id,
            p.supplier_name
          FROM products p
          INNER JOIN movement_skus ms
            ON ${sqlMovementSkuKey('p')} = ms.sku_key
          LEFT JOIN stock_by_sku sbs
            ON ms.sku_key = sbs.sku_key
          WHERE ${sqlPickProductIdForSkuAtWarehouse(catalogPickClause)}

          UNION ALL

          SELECT
            p.id,
            p.name,
            p.sku,
            p.barcode,
            p.category,
            ${rowPrice} AS price,
            p.price2,
            p.price3,
            p.price4,
            ${rowCost} AS cost,
            ${rowFirstCost} AS first_cost,
            ${rowLastCost} AS last_cost,
            ${rowAvgCost} AS avg_cost,
            ${sqlGridStockExpr('p')} AS stock,
            p.unit,
            p.tax_rate,
            p.branch_id,
            p.supplier_id,
            p.supplier_name
          FROM products p
          LEFT JOIN stock_by_sku sbs
            ON ${sqlMovementSkuKey('p')} = sbs.sku_key
          WHERE ${productActive('p')}
            AND p.branch_id = $1
            AND TRIM(COALESCE(p.sku, '')) != ''
            AND NOT EXISTS (
              SELECT 1 FROM movement_skus ms
              WHERE ms.sku_key = ${sqlMovementSkuKey('p')}
            )

          UNION ALL

          SELECT
            p.id,
            p.name,
            p.sku,
            p.barcode,
            p.category,
            ${rowPrice} AS price,
            p.price2,
            p.price3,
            p.price4,
            ${rowCost} AS cost,
            ${rowFirstCost} AS first_cost,
            ${rowLastCost} AS last_cost,
            ${rowAvgCost} AS avg_cost,
            ${sqlGridStockExpr('p')} AS stock,
            p.unit,
            p.tax_rate,
            $1 AS branch_id,
            p.supplier_id,
            p.supplier_name
          FROM products p
          LEFT JOIN stock_by_sku sbs
            ON ${sqlMovementSkuKey('p')} = sbs.sku_key
          WHERE ${productActive('p')}
            AND TRIM(COALESCE(p.sku, '')) != ''
            AND ${catalogBranchClause}
            ${sqlHideCatalogWhenFilialHasSameSku()}
            AND NOT EXISTS (
              SELECT 1 FROM movement_skus ms
              WHERE ms.sku_key = ${sqlMovementSkuKey('p')}
            )
          ORDER BY name`;
  const result = await db.query(query, params);
  return dedupeRowsBySkuFast(result.rows, branchKey, mainBranchIds);
}

function mergeConsolidatedSkuRow(bySku, row, mainBranchIds) {
  const key = normalizeSkuKey(row.sku) || String(row.id);
  const qty = Number(row.stock) || 0;
  const prev = bySku.get(key);
  if (!prev) {
    bySku.set(key, { ...row, stock: qty });
    return;
  }
  const pick =
    rowDisplayScore(row, undefined, mainBranchIds) >= rowDisplayScore(prev, undefined, mainBranchIds)
      ? row
      : prev;
  const other = pick === row ? prev : row;
  const maxN = (a, b) => Math.max(Number(a) || 0, Number(b) || 0);
  bySku.set(key, {
    ...pick,
    supplier_id: pick.supplier_id || other.supplier_id || null,
    supplier_name: pick.supplier_name || other.supplier_name || null,
    stock: (Number(prev.stock) || 0) + qty,
    price: maxN(pick.price, other.price),
    cost: maxN(pick.cost, other.cost),
    first_cost: maxN(pick.first_cost, other.first_cost),
    last_cost: maxN(pick.last_cost, other.last_cost),
    avg_cost: maxN(pick.avg_cost, other.avg_cost),
  });
}

