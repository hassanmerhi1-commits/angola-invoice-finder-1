  /** Fill supplier from another row with the same SKU when this row has none. */
  async function enrichProductSupplierFromSku(row) {
    if (!row) return row;
    const hasId = row.supplier_id != null && String(row.supplier_id).trim() !== '';
    const hasName = row.supplier_name != null && String(row.supplier_name).trim() !== '';
    if ((hasId || hasName) || !row.sku || !String(row.sku).trim()) return row;

    const sibling = await db.query(
      `SELECT supplier_id, supplier_name
       FROM products
       WHERE LOWER(TRIM(COALESCE(sku, ''))) = LOWER(TRIM($1))
         AND (
           (supplier_id IS NOT NULL AND TRIM(COALESCE(CAST(supplier_id AS TEXT), '')) != '')
           OR (supplier_name IS NOT NULL AND TRIM(COALESCE(supplier_name, '')) != '')
         )
       ORDER BY updated_at DESC NULLS LAST, created_at DESC NULLS LAST
       LIMIT 1`,
      [row.sku],
    );
    let src = sibling.rows[0];
    if (!src) {
      const bySku = await loadLatestPurchaseSupplierBySku();
      const hit = bySku.get(canonicalSkuString(row.sku).toLowerCase());
      if (hit) src = hit;
    }
    if (!src) return row;
    return {
      ...row,
      supplier_id: row.supplier_id || src.supplier_id || null,
      supplier_name: row.supplier_name || src.supplier_name || null,
    };
  }

