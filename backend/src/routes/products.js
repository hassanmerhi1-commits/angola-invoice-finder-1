/** Fast picker list for PO/PI/sales — no movement CTE or per-row price subqueries. */
async function listProductsForBranchFast(branchKey) {
  const mainBranchIds = await loadMainBranchIds();
  const mainIn =
    mainBranchIds.length > 0
      ? mainBranchIds.map((_, i) => `$${i + 2}`).join(', ')
      : "''";
  const params = [branchKey, ...mainBranchIds];
  const catalogBranchClause = catalogBranchScopeClause(db, 'p', mainIn);
  // Price 1 is the authoritative base; never blend with price2 (see sqlGridRowPriceExpr).
  const rowPrice = 'COALESCE(p.price, 0)';
  const branchStock = `CASE WHEN p.branch_id = $1 THEN COALESCE(p.stock, 0) ELSE 0 END`;

  const listSelect = `
            p.id, p.name, p.sku, p.barcode, p.category,
            ${rowPrice} AS price, p.price2, p.price3, p.price4,
            p.cost, p.first_cost, p.last_cost, p.avg_cost,
            ${branchStock} AS stock,
            p.unit, p.tax_rate, p.branch_id, p.supplier_id, p.supplier_name,
            p.is_active, p.created_at, p.updated_at`;

  const query = `
          SELECT ${listSelect}
          FROM products p
          WHERE ${productActive('p')} AND p.branch_id = $1

          UNION ALL

          SELECT
            p.id, p.name, p.sku, p.barcode, p.category,
            ${rowPrice} AS price, p.price2, p.price3, p.price4,
            p.cost, p.first_cost, p.last_cost, p.avg_cost,
            0 AS stock,
            p.unit, p.tax_rate,
            $1 AS branch_id,
            p.supplier_id, p.supplier_name,
            p.is_active, p.created_at, p.updated_at
          FROM products p
          WHERE ${productActive('p')}
            AND TRIM(COALESCE(p.sku, '')) != ''
            AND ${catalogBranchClause}
            ${sqlHideCatalogWhenFilialHasSameSku()}
          ORDER BY name`;
  const result = await db.query(query, params);
  return dedupeRowsBySkuFast(result.rows, branchKey, mainBranchIds);
}

let sellingHintsCache = null;
let sellingHintsCacheAt = 0;
const SELLING_HINTS_CACHE_MS = 120_000;

/** Best selling price per canonical SKU (catalog + filial + PVP1 on purchase lines). */
async function loadSellingPriceHintsBySku() {
  const now = Date.now();
  if (sellingHintsCache && now - sellingHintsCacheAt < SELLING_HINTS_CACHE_MS) {
    return sellingHintsCache;
  }

  const bySku = new Map();

  const productRows = await db.query(
    `SELECT ${sqlCanonicalSkuText('p')} AS sku_key, p.price, p.price2
     FROM products p
     WHERE ${productActive('p')}
       AND TRIM(COALESCE(p.sku, '')) != ''`,
  );
  for (const row of productRows.rows || []) {
    const key = String(row.sku_key || '').trim().toLowerCase();
    if (!key) continue;
    const best = Math.max(
      Number(bySku.get(key) || 0),
      Number(row.price) || 0,
      Number(row.price2) || 0,
    );
    if (best > 0) bySku.set(key, best);
  }

  try {
    const invoices = await db.query(
      `SELECT lines_json FROM purchase_invoices
       ORDER BY date DESC, updated_at DESC
       LIMIT 800`,
    );
    for (const inv of invoices.rows || []) {
      let lines = inv.lines_json;
      if (typeof lines === 'string') {
        try {
          lines = JSON.parse(lines);
        } catch {
          lines = [];
        }
      }
      if (!Array.isArray(lines)) continue;
      for (const line of lines) {
        const rawSku = line.productCode || line.product_code || '';
        const key = canonicalSkuString(rawSku).toLowerCase();
        if (!key) continue;
        const p1 = Number(line.price1 ?? line.price ?? 0);
        if (p1 > 0) bySku.set(key, Math.max(Number(bySku.get(key) || 0), p1));
      }
    }
  } catch (err) {
    console.warn('[PRODUCTS] purchase price hints:', err.message);
  }

  sellingHintsCache = bySku;
  sellingHintsCacheAt = now;
  return bySku;
}

function invalidateSellingHintsCache() {
  sellingHintsCache = null;
  sellingHintsCacheAt = 0;
}

let purchaseSupplierCache = null;
let purchaseSupplierCacheAt = 0;
